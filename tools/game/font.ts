function glyph(char: string, art: string): Glyph {
  const rows = art.split(" ");
  if (rows.length !== 7 && rows.length !== 9) throw new Error(`glyph ${JSON.stringify(char)}: ${rows.length} rows`);
  const inked = rows[0]!.length;
  if (rows.some((r) => r.length !== inked)) throw new Error(`glyph ${JSON.stringify(char)}: rows of different widths`);
  const width = inked + 1;
  const pixels = new Uint8Array(width * ROWS);
  rows.forEach((row, y) => [...row].forEach((c, x) => (pixels[y * width + x] = c === "#" ? 1 : 0)));
  return { width, height: ROWS, pixels };
}

/** The font, as a Font (write it with writeFont). */
export function pixelFont(): Font {
  const glyphs: Glyph[] = Array.from({ length: 128 }, () => ({ width: 0, height: 0, pixels: new Uint8Array(0) }));
  for (const [char, art] of Object.entries(GLYPHS)) glyphs[char.charCodeAt(0)] = glyph(char, art);
  return { height: LINE_HEIGHT, glyphs };
}
